export const GLYPH = {
  PLAY:   "\x10",
  STOP:   "\x11",
  PAUSE:  "\x12",
  MARK:   "\x13",
  BATT:   "\x14",
  SIG:    "\x15",
  CARET:  "\x16",
  BLOCK:  "\x17",
  UNRES:  "\x18",
};

export const CW = 5;   // glyph width  in dots
export const CH = 7;   // glyph height in dots
export const ADV = 6;  // one blank column between glyphs
export const LH = 9;   // one blank row and a half between lines

/* char -> Uint8Array(5), one byte per column, bit 0 = top row */
const COLS = new Map();
for (const ch in A) {
  const rows = A[ch].split("/");
  const cols = new Uint8Array(CW);
  for (let y = 0; y < CH; y++) {
    for (let x = 0; x < CW; x++) {
      if (rows[y][x] === "#") cols[x] |= 1 << y;
    }
  }
  COLS.set(ch, cols);
}

const MISSING = COLS.get("?");

/** Column bitmaps for one character, folding lowercase up. */
export function glyph(ch) {
  return COLS.get(ch) || COLS.get(ch.toUpperCase()) || MISSING;
}

/** Width in dots that `str` will occupy, without the trailing gap. */
export function measure(str) {
  return str.length ? str.length * ADV - 1 : 0;
}
